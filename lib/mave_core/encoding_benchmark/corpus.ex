defmodule MaveCore.EncodingBenchmark.Corpus do
  @moduledoc """
  The clips an encoding benchmark run measures.

  The built-in clips are generated by FFmpeg's deterministic test sources, so
  every contributor measures the same pixels without downloading or sharing
  media. They stress different encoder behavior but are not real footage; pass
  a directory of representative videos to measure those instead.

  Every clip is first turned into a lossless reference at the rendition size.
  Candidates encode that reference and are compared against it, which isolates
  the encoder settings from source decoding and scaling.
  """

  alias MaveCore.Media.RenditionSizing

  @video_extensions ~w(.mp4 .mov .mkv .webm .m4v .avi .mxf .ts)
  @frame_rate 30

  @type clip :: %{
          id: String.t(),
          description: String.t(),
          source: {:synthetic, String.t()} | {:file, Path.t()}
        }

  def frame_rate, do: @frame_rate

  @doc "Returns the built-in synthetic clips for a rendition `size`."
  @spec synthetic(String.t()) :: {:ok, [clip()]} | {:error, term()}
  def synthetic(size) do
    with {:ok, long_edge} <- RenditionSizing.target_long_edge(size) do
      geometry = "size=#{long_edge}x#{div(long_edge * 9, 16)}:rate=#{@frame_rate}"

      {:ok,
       [
         %{
           id: "motion-graphics",
           description: "Sharp edges, flat colors and moving patterns",
           source: {:synthetic, "testsrc2=#{geometry}"}
         },
         %{
           id: "fractal-zoom",
           description: "Fine detail that changes in every frame",
           source: {:synthetic, "mandelbrot=#{geometry}"}
         },
         %{
           id: "grainy-gradient",
           description: "Smooth gradients under temporal noise, prone to banding",
           source:
             {:synthetic,
              "nullsrc=#{geometry},format=yuv420p," <>
                "geq=lum='128+56*sin(3*X/W+N/40)+36*cos(2*Y/H-N/55)'" <>
                ":cb='128+44*sin(2*(X+Y)/W+N/70)':cr='128+44*cos(2*X/W-N/60)'," <>
                "noise=alls=7:allf=t:all_seed=1259"}
         },
         %{
           id: "slides",
           description: "Mostly static screen content that changes once per second",
           source:
             {:synthetic,
              "testsrc2=size=#{long_edge}x#{div(long_edge * 9, 16)}:rate=1,fps=#{@frame_rate}"}
         }
       ]}
    end
  end

  @doc "Lists the video files directly inside `directory` as clips, sorted by name."
  @spec from_directory(Path.t()) :: {:ok, [clip()]} | {:error, term()}
  def from_directory(directory) do
    case File.ls(directory) do
      {:ok, entries} ->
        entries
        |> Enum.filter(&(String.downcase(Path.extname(&1)) in @video_extensions))
        |> Enum.sort()
        |> Enum.map(fn entry ->
          %{
            id: clip_id(entry),
            description: entry,
            source: {:file, Path.join(directory, entry)}
          }
        end)
        |> case do
          [] -> {:error, {:no_videos_found, directory}}
          clips -> {:ok, uniquify(clips)}
        end

      {:error, reason} ->
        {:error, {:unreadable_source_directory, directory, reason}}
    end
  end

  @doc """
  Builds the FFmpeg arguments that write the lossless reference for `clip`.

  File sources are trimmed to `duration` seconds and scaled with the production
  rendition filter; references are 8-bit 4:2:0 like every published rendition.
  """
  @spec reference_args(clip(), String.t(), pos_integer(), Path.t()) ::
          {:ok, [String.t()]} | {:error, term()}
  def reference_args(%{source: source}, size, duration, output) do
    with {:ok, scale_filter} <- RenditionSizing.long_edge_scale_filter(size) do
      input =
        case source do
          {:synthetic, graph} -> ["-f", "lavfi", "-i", graph]
          {:file, path} -> ["-i", path, "-vf", scale_filter]
        end

      {:ok,
       ["-y", "-hide_banner"] ++
         input ++
         ["-t", Integer.to_string(duration), "-map", "0:v:0", "-map_metadata", "-1"] ++
         ["-c:v", "libx264", "-qp", "0", "-preset", "ultrafast", "-pix_fmt", "yuv420p"] ++
         ["-an", output]}
    end
  end

  defp clip_id(filename) do
    filename
    |> Path.rootname()
    |> String.downcase()
    |> String.replace(~r/[^a-z0-9]+/, "-")
    |> String.trim("-")
    |> case do
      "" -> "clip"
      id -> String.slice(id, 0, 48)
    end
  end

  defp uniquify(clips) do
    clips
    |> Enum.map_reduce(%{}, fn clip, seen ->
      count = Map.get(seen, clip.id, 0)
      id = if count == 0, do: clip.id, else: "#{clip.id}-#{count + 1}"
      {%{clip | id: id}, Map.put(seen, clip.id, count + 1)}
    end)
    |> elem(0)
  end
end
